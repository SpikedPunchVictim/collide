// Q3 with a real agent: `claude -p` stream-json under a pipe-mode shim; the daemon is SIGKILLed between two turns.
import fs from 'node:fs';
import path from 'node:path';
import { attach, spawnRun, listRuns, sleep, CLEAN, SPIKE } from '../lib/client.mjs';
import { REPO } from '../lib/runs.mjs';
import { alive, kill, newState, say, startDaemon, lines } from '../lib/common.mjs';
const state = newState('state-q3b');
process.env.S2_STATE = state;
startDaemon('setsid', state);
const turn = (t) => JSON.stringify({ type: 'user', message: { role: 'user', content: [{ type: 'text', text: t }] }, parent_tool_use_id: null, session_id: '' }) + '\n';
const r = await spawnRun({ id: 'cl', argv: [CLEAN, '-p', '--input-format', 'stream-json', '--output-format', 'stream-json', '--verbose', '--model', 'haiku', '--max-budget-usd', '0.25'], cwd: REPO, mode: 'pipe', env: { USER: process.env.USER } }, state);
const out = path.join(state, 'runs/cl/out.log');
const results = () => lines(out).map((l) => { try { return JSON.parse(l); } catch { return null; } }).filter((e) => e && e.type === 'result');
const waitResults = async (n, ms = 90000) => { const t = Date.now(); while (Date.now() - t < ms) { if (results().length >= n) return true; await sleep(300); } return false; };
let a = await attach('cl', { state });
a.input(turn('Remember the code word KIWI-884. Reply with just: stored.'));
say(`turn 1 result arrived: ${await waitResults(1)}; result text: ${JSON.stringify(results()[0]?.result)}`);
a.close();
const d = JSON.parse(fs.readFileSync(path.join(state, 'daemon.lock'), 'utf8').split('\n')[0] ? JSON.stringify(+fs.readFileSync(path.join(state, 'daemon.lock'), 'utf8').split('\n')[0]) : '0');
kill(d, 'SIGKILL');
await sleep(1500);
say(`daemon ${d} SIGKILLed; shim alive ${alive(r.run.shim_pid)}, claude alive ${alive(r.run.child_pid)}`);
const d2 = startDaemon('setsid', state);
say(`new daemon pid ${d2.info.ping.pid}; run phase: ${(await listRuns(state)).find((x) => x.id === 'cl').phase}`);
a = await attach('cl', { state });
a.input(turn('What was the code word? Reply with just the word.'));
say(`turn 2 result arrived: ${await waitResults(2)}; result text: ${JSON.stringify(results()[1]?.result)}`);
const sids = [...new Set(results().map((x) => x.session_id))];
say(`both turns in one session: ${sids.length === 1} (${sids[0]}); stdout lines in out.log: ${lines(out).length}; total_cost_usd after turn 2: ${results()[1]?.total_cost_usd}`);
a.closeStdin();
await sleep(5000);
const f = (await listRuns(state)).find((x) => x.id === 'cl');
say(`closed stdin through the new daemon: phase ${f.phase}, exit ${JSON.stringify(f.exit && { code: f.exit.code, cpu_s: +(f.exit.utime_s + f.exit.stime_s).toFixed(3), maxrss_mb: +(f.exit.maxrss_bytes / 1e6).toFixed(1) })}`);
a.close();
kill(d2.info.ping.pid);
