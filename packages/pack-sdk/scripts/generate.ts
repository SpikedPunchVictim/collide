import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { compile } from 'json-schema-to-typescript'

const header = '/* Generated by packages/pack-sdk/scripts/gen.ts. Do not edit; run `pnpm gen`. */'

/**
 * Turns a directory of `<Name>.input.json` and `<Name>.output.json` schemas into TypeScript.
 * Returns the text of each file by file name, in a stable order: one `.ts` per schema, and an `index.ts` that
 * exports the root types as `<Name>Input` and `<Name>Output`.
 */
export async function generate(schemaDir: string): Promise<Record<string, string>> {
  const schemaFiles = readdirSync(schemaDir)
    .filter((file) => /^\w+\.(input|output)\.json$/.test(file))
    .sort()
  const files: Record<string, string> = {}
  const exports: string[] = []
  for (const file of schemaFiles) {
    const [name, contract] = file.split('.') as [string, 'input' | 'output']
    const schema = JSON.parse(readFileSync(join(schemaDir, file), 'utf8'))
    const module = `${name}.${contract}`
    files[`${module}.ts`] = await compile(schema, name, {
      bannerComment: header,
      cwd: schemaDir,
      style: { semi: false, singleQuote: true, printWidth: 100 },
    })
    const alias = name + (contract === 'input' ? 'Input' : 'Output')
    exports.push(`export type { ${name} as ${alias} } from './${module}.ts'`)
  }
  files['index.ts'] = [header, ...(exports.length > 0 ? exports : ['export {}'])].join('\n') + '\n'
  return files
}
