import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, test } from 'vitest'
import { generate } from '../scripts/generate.ts'

const root = join(import.meta.dirname, '..', '..', '..')

// Each pair is a directory of schemas and the directory its TypeScript is generated into.
// Keep this list in step with scripts/gen.ts.
const pairs = [
  { schemas: join(root, 'schemas'), generated: join(import.meta.dirname, '..', 'src', 'generated') },
  {
    schemas: join(root, 'core', 'tests', 'fixtures', 'schemas'),
    generated: join(import.meta.dirname, 'fixtures', 'generated'),
  },
]

function readTsFiles(dir: string): Record<string, string> {
  const files: Record<string, string> = {}
  for (const name of readdirSync(dir).filter((n) => n.endsWith('.ts')).sort()) {
    files[name] = readFileSync(join(dir, name), 'utf8')
  }
  return files
}

test.each(pairs)('generated TypeScript in $generated matches its schemas', async ({ schemas, generated }) => {
  const expected = await generate(schemas)
  const actual = readTsFiles(generated)
  expect(Object.keys(actual), 'file list differs; run `pnpm gen`').toEqual(Object.keys(expected))
  for (const [name, text] of Object.entries(expected)) {
    expect(actual[name], `${name} is out of date; run \`pnpm gen\``).toBe(text)
  }
})

test('generation is deterministic', async () => {
  const dir = pairs[1]!.schemas
  expect(await generate(dir)).toEqual(await generate(dir))
})

test('every generated file says it is generated', async () => {
  const files = await generate(pairs[1]!.schemas)
  for (const [name, text] of Object.entries(files)) {
    expect(text, name).toMatch(/^\/\* Generated by packages\/pack-sdk\/scripts\/gen\.ts\. Do not edit; run `pnpm gen`\. \*\//)
  }
})

test('input and output types are generated separately', async () => {
  const files = await generate(pairs[1]!.schemas)
  expect(Object.keys(files)).toEqual([
    'Sample.input.ts',
    'Sample.output.ts',
    'Step.input.ts',
    'Step.output.ts',
    'index.ts',
  ])
  expect(files['Sample.input.ts']).toMatch(/labels\?: /)
  expect(files['Sample.output.ts']).toMatch(/labels: /)
})
